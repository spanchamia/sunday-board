#!/usr/bin/env python3
"""Convert the TenBy12 Firebase export into SQL for the new database.

    python3 app/supabase/import/tenby12.py <export-dir> <family-uuid> > import.sql

The output contains family data: write it outside the repo and never commit it.
Mapping follows docs/data-model.md ("Importing TenBy12"):
  * only the real family's rows (archery, LLM experiments and test users are skipped)
  * duplicate item / dish names merged
  * "every 0 weeks" -> As needed; N weeks -> Staple, restock every N*7 days
  * dish ingredient groups flattened to dish -> item
  * dish todos -> prep steps; plans -> planned meals; purchases -> item history
  * current shopping list -> list entries ("added by hand"); open todos -> tasks
Every id is derived from the Firebase id (uuid5), so re-running inserts nothing twice.
"""
import json
import sys
import uuid
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

NS = uuid.UUID('6f1c2d4e-4b7a-4c55-9a39-5ab0b5e2e0a1')
TZ = ZoneInfo('America/Los_Angeles')
MEAL_TIMES = {'breakfast': '08:00', 'school lunch': '12:00', 'lunch': '12:30', 'school snack': '15:30',
              'snack': '16:00', 'dinner': '19:00'}


def uid(kind, key):
    return str(uuid.uuid5(NS, f'{kind}:{key}'))


def q(v):
    if v is None:
        return 'null'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def clean(name):
    t = ' '.join(str(name or '').split())
    return t[:1].upper() + t[1:]


def local_date(iso):
    return datetime.fromisoformat(iso).astimezone(TZ).date().isoformat()


def ref_id(r):
    return (r or {}).get('__ref__', '').split('/')[-1] or None


def subs(doc, name):
    return doc.get('__subcollections__', {}).get(name, [])


def main(src, family):
    L = lambda f: json.loads((Path(src) / f).read_text())
    fam_doc = L('Families.json')[0]['__id__']
    mine = lambda d: ref_id(d.get('family')) == fam_doc

    out = ['-- TenBy12 import. Generated by app/supabase/import/tenby12.py. Contains family data; do not commit.', 'begin;']
    ins = lambda table, cols, rows: out.append(
        f"insert into public.{table} ({', '.join(cols)}) values\n  " +
        ',\n  '.join('(' + ', '.join(q(v) for v in r) + ')' for r in rows) + '\non conflict do nothing;') if rows else None

    # Categories: My Home (already created with the family) > Kitchen > ...; other areas directly under My Home.
    home = f"(select id from public.categories where family_id = {q(family)} and parent_id is null order by sort, created_at limit 1)"
    metas = {m['__id__']: m['name'] for m in L('meta_categories.json')}
    kitchen_id = uid('cat', 'kitchen')
    cats, cat_rows = {}, []
    item_cats = [c for c in L('item_categories.json') if mine(c) and clean(c['name'])]
    for i, c in enumerate(sorted(item_cats, key=lambda c: c['name'].lower())):
        key = clean(c['name']).lower()
        if key in cats:
            cats[c['__id__']] = cats[key]
            continue
        in_kitchen = metas.get(ref_id(c.get('meta_category'))) == 'Kitchen'
        cid = uid('cat', c['__id__'])
        cats[c['__id__']] = cats[key] = cid
        cat_rows.append((cid, clean(c['name']), i, in_kitchen))
    out.append(f"insert into public.categories (id, family_id, parent_id, name, sort) select {q(kitchen_id)}, {q(family)}, {home}, 'Kitchen', 0 on conflict do nothing;")
    out.append('insert into public.categories (id, family_id, parent_id, name, sort) values\n  ' + ',\n  '.join(
        f"({q(cid)}, {q(family)}, {q(kitchen_id) if k else home}, {q(n)}, {s})" for cid, n, s, k in cat_rows) + '\non conflict do nothing;')

    # Stores
    stores = {}
    store_rows = []
    for i, s in enumerate(sorted((s for s in L('stores.json') if mine(s)), key=lambda s: s['name'].lower())):
        sid = uid('store', s['__id__'])
        stores[s['__id__']] = sid
        store_rows.append((sid, family, clean(s['name']), i))
    ins('stores', ['id', 'family_id', 'name', 'sort'], store_rows)

    # Items (merge duplicates by name; keep the record with the most information)
    raw_items = [i for i in L('items.json') if mine(i) and clean(i['name'])]
    score = lambda i: (bool(i.get('stores')), i.get('recommended_purchase_frequency_weeks') is not None, bool(i.get('last_purchase_date')))
    canonical = {}
    for it in sorted(raw_items, key=score, reverse=True):
        canonical.setdefault(clean(it['name']).lower(), it)
    items = {}  # firebase id -> new uuid
    item_rows, item_store_rows, merged = [], set(), 0
    for it in raw_items:
        keep = canonical[clean(it['name']).lower()]
        items[it['__id__']] = uid('item', keep['__id__'])
        if keep is not it:
            merged += 1
    for it in canonical.values():
        weeks = it.get('recommended_purchase_frequency_weeks') or 0
        cat = ref_id(it.get('item_category')) or ref_id(it.get('category'))
        item_rows.append((items[it['__id__']], family, cats.get(cat), clean(it['name']),
                          'staple' if weeks > 0 else 'as_needed', weeks * 7 if weeks > 0 else None))
    for it in raw_items:
        for r in it.get('stores') or []:
            if ref_id(r) in stores:
                item_store_rows.add((items[it['__id__']], stores[ref_id(r)], family))
    for s in L('stores.json'):
        for si in subs(s, 'store_items'):
            if s['__id__'] in stores and ref_id(si.get('item')) in items:
                item_store_rows.add((items[ref_id(si['item'])], stores[s['__id__']], family))
    ins('items', ['id', 'family_id', 'category_id', 'name', 'restock_mode', 'restock_every_days'], item_rows)
    ins('item_stores', ['item_id', 'store_id', 'family_id'], sorted(item_store_rows))

    # Purchase history -> item events (one per item per day)
    events = set()
    for p in L('purchase_history.json'):
        if ref_id(p.get('item')) in items:
            events.add((items[ref_id(p['item'])], local_date(p['purchase_date'])))
    for it in raw_items:
        if it.get('last_purchase_date'):
            events.add((items[it['__id__']], local_date(it['last_purchase_date'])))
    ins('item_events', ['id', 'family_id', 'item_id', 'kind', 'happened_on'],
        [(uid('event', f'{i}:{d}'), family, i, 'bought', d) for i, d in sorted(events)])

    # Meal types
    meal_types = {}
    order = ['breakfast', 'school snack', 'school lunch', 'lunch', 'snack', 'dinner', 'salad', 'dessert', 'special occasions']
    mt_rows = []
    for dc in L('dish_categories.json'):
        if not mine(dc):
            continue
        mid = uid('meal', dc['__id__'])
        meal_types[dc['__id__']] = mid
        n = clean(dc['name'])
        sort = order.index(n.lower()) if n.lower() in order else 50
        mt_rows.append((mid, family, n, sort, MEAL_TIMES.get(n.lower())))
    ins('meal_types', ['id', 'family_id', 'name', 'sort', 'usual_time'], mt_rows)

    # Dishes (merge duplicate names)
    raw_dishes = [d for d in L('dishes.json') if mine(d) and clean(d['name'])]
    dish_keep = {}
    for d in sorted(raw_dishes, key=lambda d: d.get('recommended_frequency_weeks') is not None, reverse=True):
        dish_keep.setdefault(clean(d['name']).lower(), d)
    dishes = {d['__id__']: uid('dish', dish_keep[clean(d['name']).lower()]['__id__']) for d in raw_dishes}
    dish_rows, prep_rows, dmt = [], [], set()
    for d in dish_keep.values():
        weeks = d.get('recommended_frequency_weeks') or 0
        wd, we = d.get('recommended_weekdays'), d.get('recommended_weekends')
        if not wd and not we:
            wd = we = True
        dish_rows.append((dishes[d['__id__']], family, clean(d['name']), weeks * 7 if weeks > 0 else None, bool(wd), bool(we)))
        for i, t in enumerate(subs(d, 'dish_todos')):
            mins = int(t.get('diff') or 0) * (1440 if str(t.get('unit')).lower().startswith('day') else 60)
            prep_rows.append((uid('prep', t['__id__']), dishes[d['__id__']], family, clean(t['name']), min(mins, 20160), i))
    for d in raw_dishes:
        for r in d.get('dish_categories') or []:
            if ref_id(r) in meal_types:
                dmt.add((dishes[d['__id__']], meal_types[ref_id(r)], family))
    meal_type_items = set()
    for dc in L('dish_categories.json'):
        if dc['__id__'] not in meal_types:
            continue
        for x in subs(dc, 'dish_category_dishes'):
            if ref_id(x.get('dish')) in dishes:
                dmt.add((dishes[ref_id(x['dish'])], meal_types[dc['__id__']], family))
        for x in subs(dc, 'dish_category_items'):
            if ref_id(x.get('item')) in items:
                meal_type_items.add((meal_types[dc['__id__']], items[ref_id(x['item'])], family))
    ins('dishes', ['id', 'family_id', 'name', 'make_every_days', 'weekdays_ok', 'weekends_ok'], dish_rows)
    ins('dish_prep_steps', ['id', 'dish_id', 'family_id', 'name', 'lead_minutes', 'sort'], prep_rows)
    ins('dish_meal_types', ['dish_id', 'meal_type_id', 'family_id'], sorted(dmt))
    ins('meal_type_items', ['meal_type_id', 'item_id', 'family_id'], sorted(meal_type_items))

    ingredients = set()
    for g in L('dish_item_categories.json'):
        if ref_id(g.get('dish')) not in dishes:
            continue
        for x in subs(g, 'dish_item_category_items'):
            if ref_id(x.get('item')) in items:
                ingredients.add((dishes[ref_id(g['dish'])], items[ref_id(x['item'])], family))
    ins('dish_ingredients', ['dish_id', 'item_id', 'family_id'], sorted(ingredients))

    # Meal plans
    plans = {p['__id__']: local_date(p['date']) for p in L('plans.json') if mine(p)}
    planned = set()
    for pdc in L('plan_dish_categories.json'):
        day = plans.get(ref_id(pdc.get('plan')))
        mt = meal_types.get(ref_id(pdc.get('dish_category')))
        if not day or not mt:
            continue
        for x in subs(pdc, 'plan_dish_category_dishes'):
            if ref_id(x.get('dish')) in dishes:
                planned.add((day, mt, dishes[ref_id(x['dish'])]))
    ins('planned_meals', ['id', 'family_id', 'date', 'meal_type_id', 'dish_id'],
        [(uid('planned', f'{d}:{m}:{x}'), family, d, m, x) for d, m, x in sorted(planned)])

    # Current shopping list -> open list entries ("added by hand")
    on_list = set()
    for s in L('shopping_list.json'):
        if ref_id(s.get('item')) in items:
            on_list.add(items[ref_id(s['item'])])
    for c in L('shopping_list_item_categories.json'):
        for x in subs(c, 'shopping_list_items'):
            if ref_id(x.get('item')) in items:
                on_list.add(items[ref_id(x['item'])])
    entries = [(uid('entry', i), family, i) for i in sorted(on_list)]
    ins('list_entries', ['id', 'family_id', 'item_id'], entries)
    ins('list_entry_reasons', ['id', 'entry_id', 'family_id', 'reason'],
        [(uid('reason', e[0]), e[0], family, 'manual') for e in entries])

    # Open to-dos (shared with the family; owner = whoever runs the import is not known, so the family owner)
    owner = f"(select user_id from public.family_members where family_id = {q(family)} and role = 'owner' limit 1)"
    todos = [t for t in L('todos.json') if mine(t) and not t.get('done')]
    if todos:
        out.append('insert into public.tasks (id, family_id, title, due_on, owner_id) values\n  ' + ',\n  '.join(
            f"({q(uid('task', t['__id__']))}, {q(family)}, {q(clean(t['name']))}, {q(local_date(t['date_time']))}, {owner})"
            for t in todos) + '\non conflict do nothing;')

    out.append('commit;')
    print('\n'.join(out))
    print(f'-- {len(cat_rows)} categories, {len(store_rows)} stores, {len(item_rows)} items ({merged} duplicates merged), '
          f'{len(item_store_rows)} item-store links, {len(events)} purchases, {len(mt_rows)} meal types, '
          f'{len(dish_rows)} dishes, {len(prep_rows)} prep steps, {len(ingredients)} ingredients, '
          f'{len(planned)} planned dishes, {len(entries)} list items, {len(todos)} open to-dos', file=sys.stderr)


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
